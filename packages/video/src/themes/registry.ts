/** The full look of a theme. `classic` is the owner's brand exactly as before themes existed. */
export function resolveTheme(id: ThemeId, brand: Brand): ResolvedTheme {
  if (id === 'classic') {
    return {
      id,
      brand,
      headingFont: brand.font,
      bodyFont: brand.font,
      charWidth: 0.55,
      uppercase: false,
      background: 'brand',
      surface: 'brand',
      sticker: 'pill',
      ink: { stroke: brand.text, fill: brand.surface, accent: brand.accent, width: 6, drawOn: false, boil: 0 },
      presenter: 'mascot',
      onBg: { text: brand.text, accent: brand.accent },
      caption: { backdrop: brand.bg, plate: false, spoken: brand.text, keyword: brand.accent, upcoming: CLASSIC_UPCOMING },
      confetti: [brand.accent, brand.accent2, ...CLASSIC_CONFETTI],
    };
  }
  const { colors, ...look } = LOOKS[id];
  return { id, ...look, brand: { ...colors, font: look.bodyFont, handle: brand.handle } };
}
