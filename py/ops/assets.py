"""Built-in sound effects and background beats, synthesised with numpy.

Everything here is generated by code, so it is original and free of licences. Output is
deterministic (fixed seeds) and only missing files are written.
"""

import os

import numpy as np
import soundfile as sf

SR = 44100
# Bump when any built-in sound changes: older folders are regenerated (see assets()).
# Must equal AUDIO_ASSETS_VERSION in packages/shared/src/effects.ts.
ASSETS_VERSION = 2
SFX = ["swipe", "tick", "bubble", "ding", "boom", "riser"]
OBSOLETE_SFX = ["whoosh", "pop"]  # version 1 names
MUSIC = ["lofi", "upbeat", "dramatic"]
LABELS = {"lofi": "Lo-fi chill", "upbeat": "Upbeat pop", "dramatic": "Dramatic"}


# ---------- small building blocks ----------


def _t(sec):
    return np.arange(int(SR * sec)) / SR


def _env(n, attack, release_rate):
    """Fast attack, exponential decay envelope of n samples."""
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-t * release_rate)


def _lowpass(x, cutoff_hz):
    """One-pole low-pass (cutoff may be an array for sweeps)."""
    cutoff = np.broadcast_to(np.asarray(cutoff_hz, dtype=np.float64), x.shape)
    alpha = 1 - np.exp(-2 * np.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):  # short signals only (effects, single notes)
        acc += alpha[i] * (x[i] - acc)
        y[i] = acc
    return y


def _norm(x, peak=0.9):
    m = np.max(np.abs(x))
    return x * (peak / m) if m > 0 else x


def _note_hz(midi):
    return 440.0 * 2 ** ((midi - 69) / 12)


# ---------- sound effects ----------


def _level(x, rms_db=-24.0, peak=0.95):
    """Set loudness by RMS (not peak), so short and long effects sound equally loud."""
    rms = np.sqrt(np.mean(x**2))
    return np.clip(x * (10 ** (rms_db / 20) / rms), -peak, peak) if rms > 0 else x


def _swipe(rng):
    """Short, muted swipe, like a card sliding (owner's pick to replace the hissy whoosh)."""
    n = int(SR * 0.3)
    t = np.arange(n) / n
    noise = rng.standard_normal(n)
    dark = _lowpass(_lowpass(noise, 1100), 1100)  # two passes: no hiss
    band = dark - _lowpass(dark, 300)
    return _level(band * np.sin(np.pi * t) ** 1.5)


def _tick(rng):
    """Gentle wooden tick: a short low tone, no noise at all."""
    t = _t(0.12)
    tone = np.sin(2 * np.pi * 520 * t) + 0.35 * np.sin(2 * np.pi * 1040 * t)
    return _level(tone * np.exp(-t * 45) * np.clip(t / 0.002, 0, 1))


def _bubble(rng):
    """Soft rising 'bloop': a rounded sine sweep."""
    t = _t(0.22)
    f = 280 + 420 * (t / t[-1]) ** 1.5
    tone = np.sin(2 * np.pi * np.cumsum(f) / SR)
    return _level(tone * np.sin(np.pi * t / t[-1]) ** 1.2)


def _ding(rng):
    t = _t(1.1)
    partials = [(1.0, 1.0), (2.76, 0.45), (5.4, 0.2), (2.0, 0.25)]
    x = sum(a * np.sin(2 * np.pi * 1046.5 * k * t) * np.exp(-t * (3 + 2 * k)) for k, a in partials)
    return _norm(x * np.clip(t / 0.003, 0, 1), 0.7)


def _boom(rng):
    t = _t(1.2)
    f = 35 + 55 * np.exp(-t * 6)
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 3.2)
    hit = _lowpass(rng.standard_normal(len(t)), 900) * np.exp(-t * 30)
    return _norm(body + 0.5 * hit, 0.85)


def _riser(rng):
    t = _t(1.2)
    p = t / t[-1]
    f = 200 + 1000 * p**2
    tone = np.sin(2 * np.pi * np.cumsum(f) / SR) * 0.4
    air = _lowpass(rng.standard_normal(len(t)), 500 + 6000 * p) * 0.6
    return _norm((tone + air) * p**1.6 * (1 - np.clip((p - 0.97) / 0.03, 0, 1)), 0.7)


SFX_MAKERS = {"swipe": _swipe, "tick": _tick, "bubble": _bubble, "ding": _ding, "boom": _boom, "riser": _riser}


# ---------- drum + synth voices for beats ----------


def _kick(rng, punch=1.0):
    t = _t(0.35)
    f = 45 + 90 * np.exp(-t * 28)
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9) * punch


def _snare(rng):
    t = _t(0.2)
    noise = rng.standard_normal(len(t))
    noise = noise - _lowpass(noise, 1200)  # keep the bright part
    tone = np.sin(2 * np.pi * 185 * t)
    return (0.7 * noise + 0.4 * tone) * np.exp(-t * 22)


def _hat(rng, open_=False):
    t = _t(0.18 if open_ else 0.05)
    noise = rng.standard_normal(len(t))
    noise = noise - _lowpass(noise, 6000)
    return noise * np.exp(-t * (18 if open_ else 80)) * 0.35


def _pad(midis, sec, bright):
    t = _t(sec)
    x = sum(np.sin(2 * np.pi * _note_hz(m) * t) + 0.3 * np.sin(2 * np.pi * _note_hz(m) * 1.003 * t) for m in midis)
    x = _lowpass(x, bright)
    edge = np.clip(t / 0.08, 0, 1) * np.clip((sec - t) / 0.2, 0, 1)
    return x * edge / len(midis)


def _bass(midi, sec):
    t = _t(sec)
    f = _note_hz(midi)
    x = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * 2 * f * t)
    return x * np.clip(t / 0.01, 0, 1) * np.exp(-t * 1.2)


def _place(track, sound, at_sec, gain=1.0):
    i = int(at_sec * SR)
    j = min(len(track), i + len(sound))
    if i < len(track):
        track[i:j] += sound[: j - i] * gain


def _beat(style, rng):
    bpm = {"lofi": 78, "upbeat": 116, "dramatic": 88}[style]
    beat = 60 / bpm
    bars = 12 if style == "lofi" else 16
    total = bars * 4 * beat
    track = np.zeros(int(SR * total) + SR)
    # 4-bar chord loops (MIDI notes)
    prog = {
        "lofi": [[57, 60, 64, 67], [53, 57, 60, 64], [48, 52, 55, 59], [55, 59, 62, 65]],  # Am7 Fmaj7 Cmaj7 G7
        "upbeat": [[60, 64, 67], [55, 59, 62], [57, 60, 64], [53, 57, 60]],  # C G Am F
        "dramatic": [[57, 60, 64], [53, 57, 60], [50, 53, 57], [52, 56, 59]],  # Am F Dm E
    }[style]
    bright = {"lofi": 1400, "upbeat": 3800, "dramatic": 1800}[style]
    kick, snare = _kick(rng), _snare(rng)
    for bar in range(bars):
        start = bar * 4 * beat
        chord = prog[bar % 4]
        _place(track, _pad(chord, 4 * beat, bright), start, 0.5 if style != "upbeat" else 0.4)
        _place(track, _bass(chord[0] - 24, 4 * beat), start, 0.55)
        for b in range(4):
            at = start + b * beat
            if style == "upbeat":
                _place(track, kick, at, 0.9)
                if b % 2:
                    _place(track, snare, at, 0.55)
                _place(track, _hat(rng), at + beat / 2, 0.8)
            elif style == "lofi":
                if b in (0, 2) or (b == 3 and bar % 2):
                    _place(track, kick, at + (0.04 if b == 3 else 0), 0.75)
                if b in (1, 3):
                    _place(track, snare, at, 0.4)
                swing = beat * 0.58
                _place(track, _hat(rng), at, 0.5)
                _place(track, _hat(rng), at + swing, 0.35)
            else:  # dramatic: sparse, heavy, tension builds every 4 bars
                if b == 0:
                    _place(track, _kick(rng, 1.3), at, 1.0)
                if b == 2 and bar % 2:
                    _place(track, snare, at, 0.6)
                _place(track, _hat(rng, open_=(b == 3)), at + beat / 2, 0.4)
        if style == "dramatic" and bar % 4 == 3:
            _place(track, _riser(rng) * 0.5, start + 4 * beat - 1.2, 0.6)
    if style == "lofi":
        crackle = np.zeros_like(track)
        idx = rng.integers(0, len(track), size=int(total * 25))
        crackle[idx] = rng.uniform(-0.3, 0.3, size=len(idx))
        track += _lowpass(crackle, 3000) * 0.4
    track = track[: int(SR * total)]
    fade = int(SR * 0.05)  # no click when the loop restarts
    track[:fade] *= np.linspace(0, 1, fade)
    track[-fade:] *= np.linspace(1, 0, fade)
    return _norm(track, 0.8)


# ---------- op ----------


def _write(path, audio):
    tmp = path + ".tmp.wav"
    sf.write(tmp, audio.astype(np.float32), SR, subtype="PCM_16")
    os.replace(tmp, path)


def assets(args: dict, progress=None) -> dict:
    """Write any missing built-in sounds under args['dir'] (sfx/*.wav, music/builtin-*.wav)."""
    root = args["dir"]
    os.makedirs(os.path.join(root, "sfx"), exist_ok=True)
    os.makedirs(os.path.join(root, "music"), exist_ok=True)
    version_file = os.path.join(root, "version.txt")
    current = open(version_file, encoding="utf-8").read().strip() if os.path.exists(version_file) else ""
    if current != str(ASSETS_VERSION):
        # made by an older version: drop every built-in so it is regenerated (uploads are untouched)
        for name in SFX + OBSOLETE_SFX:
            p = os.path.join(root, "sfx", f"{name}.wav")
            if os.path.exists(p):
                os.remove(p)
        for m in MUSIC:
            p = os.path.join(root, "music", f"builtin-{m}.wav")
            if os.path.exists(p):
                os.remove(p)
    jobs = [("sfx", name, f"{name}.wav") for name in SFX] + [("music", m, f"builtin-{m}.wav") for m in MUSIC]
    for k, (kind, name, file) in enumerate(jobs):
        path = os.path.join(root, kind, file)
        if os.path.exists(path):
            continue
        if progress:
            progress(k / len(jobs), f"making {file}")
        rng = np.random.default_rng(sum(map(ord, name)))  # fixed seed per sound
        audio = SFX_MAKERS[name](rng) if kind == "sfx" else _beat(name, rng)
        _write(path, audio)
    with open(version_file, "w", encoding="utf-8") as f:
        f.write(str(ASSETS_VERSION))
    return {"sfx": SFX, "music": [f"builtin-{m}.wav" for m in MUSIC], "labels": LABELS}
